CREATE TABLE reference_item (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR2(20)  NOT NULL,
    code        VARCHAR2(50)  NOT NULL,
    label       VARCHAR2(200) NOT NULL,
    description VARCHAR2(1000),
    status      VARCHAR2(20)  NOT NULL,
    version     NUMBER(10)    NOT NULL,
    published   NUMBER(1)     DEFAULT 0 NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by  VARCHAR2(50)  NOT NULL,
    CONSTRAINT uk_reference_type_code UNIQUE (type, code)
);

CREATE TABLE reference_version (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_id NUMBER(19)    NOT NULL,
    version      NUMBER(10)    NOT NULL,
    action       VARCHAR2(20)  NOT NULL,
    label        VARCHAR2(200) NOT NULL,
    description  VARCHAR2(1000),
    status       VARCHAR2(20)  NOT NULL,
    changed_by   VARCHAR2(50)  NOT NULL,
    changed_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_reference_version_ref ON reference_version (reference_id);
